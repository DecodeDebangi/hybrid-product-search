"""Generate "colour + usage + product type" queries (e.g. "black formal watches") from random catalog combinations.

Queries are sampled, not hand-picked, so the set can't be tilted toward cases a given change handles well.
"""

import argparse
import json
import os
import random
from pathlib import Path

import httpx

from .paths import REPO_ROOT

USAGES = ["Casual", "Formal", "Sports", "Ethnic", "Party"]
MIN_PRODUCTS = 10  # skip combinations too rare to have a meaningful relevant set


def combinations(solr_url: str) -> list[tuple[str, str, str, int]]:
    """(article_type, base_colour, usage, count) for every combination in the catalog."""
    facet = {
        "types": {
            "type": "terms",
            "field": "article_type",
            "limit": -1,
            "facet": {
                "colours": {
                    "type": "terms",
                    "field": "base_colour",
                    "limit": -1,
                    "facet": {"usages": {"type": "terms", "field": "usage", "limit": -1}},
                }
            },
        }
    }
    res = httpx.post(f"{solr_url}/select", json={"query": "*:*", "limit": 0, "facet": facet}, timeout=60)
    res.raise_for_status()
    return [
        (t["val"], c["val"], u["val"], u["count"])
        for t in res.json()["facets"]["types"]["buckets"]
        for c in t["colours"]["buckets"]
        for u in c["usages"]["buckets"]
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--solr-url", default=os.getenv("SOLR_URL", "http://localhost:8983/solr/products"))
    parser.add_argument("--size", type=int, default=40)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "eval" / "queries_attribute.json")
    args = parser.parse_args()

    candidates = sorted(
        (article_type, colour, usage)
        for article_type, colour, usage, count in combinations(args.solr_url)
        if count >= MIN_PRODUCTS
        and usage in USAGES
        # "black formal formal shoes" is not a query anyone types.
        and usage.lower() not in article_type.lower()
    )
    sample = random.Random(args.seed).sample(candidates, args.size)

    queries = [
        {
            "id": f"at{i:02d}",
            "category": "attribute",
            "query": f"{colour} {usage} {article_type}".lower(),
            "must": {"article_type": [article_type]},
            "should": {"base_colour": [colour], "usage": [usage]},
        }
        for i, (article_type, colour, usage) in enumerate(sample, start=1)
    ]
    about = (
        f"Generated by product-search-attribute-queries (seed {args.seed}): {args.size} random colour + usage + "
        f"product-type combinations with at least {MIN_PRODUCTS} products each, out of {len(candidates)} candidates. "
        "Relevant = right product type; perfect = also right colour and usage."
    )
    lines = ["{", f'  "about": {json.dumps(about)},', '  "queries": [']
    lines += [f"    {json.dumps(q)}{',' if i < len(queries) - 1 else ''}" for i, q in enumerate(queries)]
    lines += ["  ]", "}"]
    args.out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(queries)} queries to {args.out}")
